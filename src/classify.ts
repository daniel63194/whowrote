import { formatIdentity, parseIdentity, sameIdentity } from './identity.js';
import { compiledTool, footerTools, matchIdentity, modelFrom, toolByAlias, toolNamedAtStart, trailerTool, type CompiledTool } from './registry.js';
import type {
  CommitInput,
  Evidence,
  GitHubCommit,
  GitHubPullRequest,
  Identity,
  IdentityInput,
  PullRequestInput,
  Result,
  ToolUse,
  Verdict,
} from './types.js';

/** Longer messages are only read up to this many characters. */
const MAX_TEXT = 200_000;
const MAX_LINE = 1_000;

const NEGATIVE = /^(?:no|none|false|n\/?a|nope|0|-+)\.?$/i;
const AI_WORD = /\b(?:ai|llm|gpt|chatgpt|claude|gemini|copilot|codex|agent)\b/i;
const TRAILER = /^([A-Za-z][A-Za-z0-9-]{0,63}):[ \t]*(\S.*)$/;

// The line must start with the disclosure (after a little markup such as "🤖 ", "> ", "*" or "<sub>", and
// an optional label like "AI disclosure:"), and a line-initial verb must be capitalised, so that wrapped
// prose ("…notifications are\ngenerated by Codex itself") does not count.
const DISCLOSURE = new RegExp(
  String.raw`^[\W_]{0,8}(?:<su[bp]>)?(?:[A-Z][A-Za-z -]{0,29}:[ \t]{0,3})?` +
    String.raw`(?:(?:This|The) (?:pull request|PR|commit|change|patch|code) (?:was|is) (?:generated|authored|created|written|made|implemented|drafted)|` +
    String.raw`Generated|Authored|Created|Written|Made|Built|Implemented|Drafted|Co-authored)` +
    String.raw` (?:with|by|using|in)(?: (?:the )?(?:help|assistance) (?:of|from))?(?: the)? \[?(?<tool>[^\]\n()]{2,60})`,
  'gmu',
);

type AuthorRole = 'ai' | 'bot' | 'human';

class Collector {
  readonly evidence: Evidence[] = [];
  private readonly seen = new Set<string>();

  add(e: Evidence): Evidence {
    const key = `${e.signal}\u0000${e.tool ?? ''}\u0000${e.value}`;
    if (!this.seen.has(key)) {
      this.seen.add(key);
      this.evidence.push(e);
    }
    return e;
  }
}

function evidence(
  signal: Evidence['signal'],
  value: string,
  kind: Evidence['kind'],
  tool?: CompiledTool,
  model?: string,
  scope: Evidence['scope'] = 'code',
): Evidence {
  const e: Evidence = { signal, value, kind, scope };
  if (tool) e.tool = tool.tool.id;
  if (model) e.model = model;
  return e;
}

/** Records the identity in the author (or committer) position. Returns what kind of author it is. */
function readAuthor(c: Collector, id: Identity, signal: 'author' | 'committer'): { role: AuthorRole; evidence?: Evidence } {
  const m = matchIdentity(id);
  const value = formatIdentity(id);
  switch (m.type) {
    case 'tool': {
      if (!m.tool.ai) return signal === 'author' ? { role: 'bot', evidence: c.add(evidence(signal, value, 'bot', m.tool)) } : { role: 'human' };
      return { role: 'ai', evidence: c.add(evidence(signal, value, 'ai', m.tool, m.model)) };
    }
    case 'marker':
      c.add(evidence('name-marker', value, 'ai', m.tool));
      return { role: 'human' };
    case 'bot':
      return signal === 'author' ? { role: 'bot', evidence: c.add(evidence(signal, value, 'bot')) } : { role: 'human' };
    default:
      return { role: 'human' };
  }
}

/** Reads trailers and footers from a commit message or pull request description. */
function readMessage(c: Collector, raw: string | null | undefined): void {
  if (typeof raw !== 'string' || raw === '') return;
  const text = raw.length > MAX_TEXT ? raw.slice(0, MAX_TEXT) : raw;

  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line.length > MAX_LINE || !line.includes(':')) continue;
    const m = TRAILER.exec(line);
    if (!m) continue;
    readTrailer(c, m[1]!.toLowerCase(), m[2]!.trim(), line);
  }

  for (const t of footerTools) {
    for (const f of t.footers) {
      const m = f.re.exec(text);
      if (m) c.add(evidence('footer', excerpt(m[0]), 'ai', t, undefined, f.scope));
    }
  }

  // Disclosure lines: "🤖 Generated with [Claude Code](…)", "Made with [Cursor](…)",
  // "> This pull request was created with GitHub Copilot.", "AI disclosure: Created with codex and …".
  for (const m of text.matchAll(DISCLOSURE)) {
    const named = m.groups?.['tool'] ?? '';
    const t = toolNamedAtStart(named);
    if (!t?.ai) continue;
    // A reviewer "writing" something is a summary of the change, not the change.
    c.add(evidence('footer', excerpt(m[0]), 'ai', t, undefined, t.tool.kind === 'ai-reviewer' ? 'message' : 'code'));
  }
}

function readTrailer(c: Collector, key: string, value: string, line: string): void {
  switch (key) {
    case 'co-authored-by':
    case 'co-developed-by': {
      const id = parseIdentity(value);
      const m = matchIdentity(id);
      if (m.type === 'tool' && m.tool.ai) c.add(evidence('co-author', formatIdentity(id), 'ai', m.tool, m.model));
      else if (m.type === 'marker') c.add(evidence('co-author', formatIdentity(id), 'ai', m.tool));
      return;
    }
    case 'assisted-by':
    case 'ai-assisted':
    case 'ai-assisted-by':
    case 'agent-assisted': {
      if (NEGATIVE.test(value)) return;
      const id = parseIdentity(value);
      const m = matchIdentity(id);
      if (m.type === 'tool') {
        if (m.tool.ai) c.add(evidence('trailer', line, 'ai', m.tool, m.model ?? modelIn(m.tool, value)));
        return;
      }
      // "Assisted-by: Jane Doe <jane@example.com>" credits a person, not a tool.
      if (key === 'assisted-by' && (id.email !== undefined || m.type === 'bot')) return;
      const t = toolByAlias(value);
      c.add(evidence('trailer', line, 'ai', t?.ai ? t : undefined, t?.ai ? modelIn(t, value) : undefined));
      return;
    }
    case 'generated-by':
    case 'made-with': {
      if (NEGATIVE.test(value)) return;
      const t = toolByAlias(value);
      if (t?.ai) c.add(evidence('trailer', line, 'ai', t, modelIn(t, value)));
      else if (!t && AI_WORD.test(value)) c.add(evidence('trailer', line, 'ai'));
      return;
    }
    default: {
      const t = trailerTool(key);
      if (t) c.add(evidence('trailer', line, t.ai ? 'ai' : 'bot', t));
    }
  }
}

/** The model named in a trailer value: `Claude:claude-opus-4` → `claude-opus-4`, `Copilot (GPT-5)` → `GPT-5`. */
function modelIn(t: CompiledTool, value: string): string | undefined {
  const fromPattern = modelFrom(t, value);
  if (fromPattern) return fromPattern;
  const colon = value.indexOf(':');
  if (colon !== -1 && !value.slice(colon).startsWith('://')) {
    const m = value.slice(colon + 1).trim().split(/\s+/)[0];
    if (m) return m;
  }
  const open = value.indexOf('(');
  const close = value.indexOf(')', open + 1);
  if (open !== -1 && close > open + 1) return value.slice(open + 1, close).trim();
  return undefined;
}

function excerpt(s: string): string {
  const one = s.replace(/\s+/g, ' ').trim();
  return one.length > 120 ? `${one.slice(0, 119)}…` : one;
}

function verdictFor(role: AuthorRole, all: Evidence[], authorEvidence: Evidence | undefined): Verdict {
  const aiCode = all.some((e) => e !== authorEvidence && e.kind === 'ai' && e.scope === 'code');
  if (role === 'ai') return 'ai-agent';
  if (role === 'bot') return aiCode ? 'ai-agent' : 'bot';
  return aiCode ? 'ai-assisted' : 'human';
}

function result(verdict: Verdict, all: Evidence[]): Result {
  const uses = new Map<string, ToolUse>();
  for (const e of all) {
    if (!e.tool || e.scope !== 'code') continue;
    let u = uses.get(e.tool);
    if (!u) {
      const t = compiledTool(e.tool)!.tool;
      u = { ...t, signals: [], models: [] };
      uses.set(e.tool, u);
    }
    if (!u.signals.includes(e.signal)) u.signals.push(e.signal);
    if (e.model && !u.models.includes(e.model)) u.models.push(e.model);
  }
  return { verdict, ai: verdict === 'ai-agent' || verdict === 'ai-assisted', tools: [...uses.values()], evidence: all };
}

function isGitHubCommit(x: unknown): x is GitHubCommit {
  return typeof x === 'object' && x !== null && typeof (x as { commit?: unknown }).commit === 'object' && (x as { commit?: unknown }).commit !== null;
}

function fromGitHubCommit(g: GitHubCommit): CommitInput {
  const merge = (git?: { name?: string | null; email?: string | null } | null, gh?: { login?: string | null; type?: string | null } | null): Identity => ({
    name: git?.name, email: git?.email, login: gh?.login, type: gh?.type,
  });
  return { message: g.commit.message, author: merge(g.commit.author, g.author), committer: merge(g.commit.committer, g.committer) };
}

function classifyCommitInto(c: Collector, input: CommitInput | GitHubCommit): { role: AuthorRole; authorEvidence?: Evidence } {
  const commit = isGitHubCommit(input) ? fromGitHubCommit(input) : input;
  const author = parseIdentity(commit.author);
  const a = readAuthor(c, author, 'author');
  const committer = parseIdentity(commit.committer);
  if (Object.keys(committer).length > 0 && !sameIdentity(author, committer)) readAuthor(c, committer, 'committer');
  readMessage(c, commit.message);
  return a.evidence ? { role: a.role, authorEvidence: a.evidence } : { role: a.role };
}

/**
 * Classifies a commit from its author, committer and message. Accepts plain objects
 * (`{ message, author: 'Jane <jane@example.com>' }`) or commit objects from the GitHub REST API.
 *
 * ```js
 * classifyCommit({
 *   author: 'Jane Doe <jane@example.com>',
 *   message: 'Fix retry\n\nCo-Authored-By: Claude Opus 4.6 <noreply@anthropic.com>',
 * }).verdict // 'ai-assisted'
 * ```
 */
export function classifyCommit(input: CommitInput | GitHubCommit): Result {
  const c = new Collector();
  const { role, authorEvidence } = classifyCommitInto(c, input);
  return result(verdictFor(role, c.evidence, authorEvidence), c.evidence);
}

function isGitHubPullRequest(x: PullRequestInput | GitHubPullRequest): x is GitHubPullRequest {
  return 'user' in x && !('author' in x);
}

/**
 * Classifies a pull request from its author, title, description and (optionally) its commits. Accepts plain
 * objects or pull request objects from the GitHub REST API and webhooks.
 */
export function classifyPullRequest(input: PullRequestInput | GitHubPullRequest): Result {
  const pr: PullRequestInput = isGitHubPullRequest(input)
    ? { author: input.user ? { login: input.user.login, type: input.user.type } : null, title: input.title, body: input.body }
    : input;
  const c = new Collector();
  const a = readAuthor(c, parseIdentity(pr.author), 'author');
  readMessage(c, [pr.title, pr.body].filter((s): s is string => typeof s === 'string').join('\n\n'));
  for (const commit of pr.commits ?? []) {
    const inner = new Collector();
    classifyCommitInto(inner, commit);
    // A commit authored by an agent inside a person's pull request is AI involvement, not the PR's author.
    for (const e of inner.evidence) if (e.kind === 'ai') c.add(e);
  }
  return result(verdictFor(a.role, c.evidence, a.evidence), c.evidence);
}

/**
 * Classifies an account or git identity on its own: `classifyActor('dependabot[bot]').verdict === 'bot'`.
 * The verdict is `ai-agent` for AI tools' own accounts, `bot` for automation, `ai-assisted` for identities
 * that carry an AI marker (aider's "Jane Doe (aider)"), and otherwise `human`.
 */
export function classifyActor(input: IdentityInput): Result {
  const c = new Collector();
  const a = readAuthor(c, parseIdentity(input), 'author');
  const verdict: Verdict = a.role === 'ai' ? 'ai-agent' : a.role === 'bot' ? 'bot' : c.evidence.length > 0 ? 'ai-assisted' : 'human';
  return result(verdict, c.evidence);
}

/** `true` for automation and AI agent accounts: `isBot('dependabot[bot]')`, `isBot({ login: 'Copilot', type: 'Bot' })`. */
export function isBot(input: IdentityInput): boolean {
  const v = classifyActor(input).verdict;
  return v === 'bot' || v === 'ai-agent';
}

/** `true` when nothing marks the identity as automation or an AI agent. Handy for filtering contributor lists. */
export function isHuman(input: IdentityInput): boolean {
  return !isBot(input);
}

/** `true` when the identity is an AI tool, or a person's identity marked as AI-assisted. */
export function isAI(input: IdentityInput): boolean {
  return classifyActor(input).ai;
}

/** The registry tool an identity belongs to, if any. */
export function identify(input: IdentityInput): ToolUse | undefined {
  return classifyActor(input).tools[0];
}
